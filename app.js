  function recalculateAllSectionHeights() {
    // Recalculate all expanded section heights
    document.querySelectorAll('.section-toggle:not(.collapsed)').forEach(toggle => {
      const content = toggle.nextElementSibling;
      if (content) {
        content.style.transition = 'none';
        content.style.maxHeight = 'none';

        void content.offsetHeight;

        const height = content.scrollHeight;

        content.style.transition = '';
        if (height > 0) {
          content.style.maxHeight = `${height}px`;
        }
      }
    });

    // Recalculate all expanded sub-section heights
    document.querySelectorAll('.sub-section-header:not(.collapsed)').forEach(header => {
      const content = header.nextElementSibling;
      if (content) {
        content.style.transition = 'none';
        content.style.maxHeight = 'none';
        void content.offsetHeight;

        const height = content.scrollHeight;

        content.style.transition = '';
        if (height > 0) {
          content.style.maxHeight = `${height}px`;
        }
      }
    });
  }

  // Expand from 0 to natural height: measure uncapped with transitions
  // off, then animate
  function animateExpand(content) {
    content.style.transition = 'none';
    content.style.maxHeight = 'none';
    void content.offsetHeight; // Force reflow

    const targetHeight = content.scrollHeight;
    content.style.transition = '';

    if (targetHeight > 0) {
      content.style.maxHeight = '0';
      void content.offsetHeight;
      content.style.maxHeight = `${targetHeight}px`;
    }
  }

  function initCollapsibleSections() {
    const sections = document.querySelectorAll('.section-toggle');
    sections.forEach(toggle => {
      const sectionName = toggle.getAttribute('data-section');
      const content = toggle.nextElementSibling;

      const defaults = {
        datasource: false,    // Data Source expanded by default
        stats: false,         // Stats expanded by default
        display: true,        // Display Options collapsed by default
        accuracy: true,       // Accuracy Filter collapsed by default
        altitude: true,       // Altitude Gradient collapsed by default
        debug: true           // Debug collapsed by default
      };

      const defaultCollapsed = defaults[sectionName] !== undefined ? defaults[sectionName] : false;
      const wasCollapsed = getSetting(`section_${sectionName}_collapsed`, defaultCollapsed);

      if (wasCollapsed) {
        toggle.classList.add('collapsed');
        content.style.maxHeight = '0';
      } else {
        // No maxHeight during init - set later once async content has loaded
        content.style.maxHeight = 'none';
      }

      toggle.addEventListener('click', () => {
        const willCollapse = !toggle.classList.contains('collapsed');
        saveSetting(`section_${sectionName}_collapsed`, willCollapse, defaultCollapsed);

        if (willCollapse) {
          toggle.classList.add('collapsed');
          content.style.maxHeight = '0';
        } else {
          // Remove collapsed class FIRST to restore padding
          toggle.classList.remove('collapsed');
          animateExpand(content);
          // Viewport counts are skipped while the section is hidden
          if (sectionName === 'stats') updateViewportStats();
        }
      });
    });

    const subSections = document.querySelectorAll('.sub-section-header');
    subSections.forEach(header => {
      const subName = header.getAttribute('data-sub');
      const content = header.nextElementSibling;
      const settingKey = `sub_${subName}_collapsed`;
      // Config files may pin a different default collapse state; a stored
      // local value still wins over it. saveSetting compares against the
      // same default, so clicking back to the configured state drops the
      // local override instead of storing a redundant copy
      const configDefault = getNestedConfigValue(CONFIG_PATHS[settingKey]) ?? true;
      const wasCollapsed = getSetting(settingKey, configDefault);

      if (wasCollapsed) {
        header.classList.add('collapsed');
        content.style.maxHeight = '0';
      } else {
        content.style.maxHeight = 'none';
      }

      // The parent section-content must re-measure after a sub-section
      // animates, or its max-height caps the wrong value
      const expandedParentContent = () => {
        const parentSection = header.closest('.sidebar-section');
        const parentContent = parentSection?.querySelector(':scope > .section-content');
        const parentToggle = parentSection?.querySelector(':scope > .section-toggle');
        return (parentContent && !parentToggle?.classList.contains('collapsed'))
          ? parentContent
          : null;
      };

      const remeasureParent = () => {
        const parentContent = expandedParentContent();
        if (!parentContent) return;

        parentContent.style.transition = 'none';
        parentContent.style.maxHeight = 'none';
        void parentContent.offsetHeight; // Force reflow

        const height = parentContent.scrollHeight;
        parentContent.style.transition = '';
        if (height > 0) {
          parentContent.style.maxHeight = `${height}px`;
        }
      };

      header.addEventListener('click', () => {
        const willCollapse = !header.classList.contains('collapsed');
        saveSetting(settingKey, willCollapse, configDefault);

        if (willCollapse) {
          header.classList.add('collapsed');
          content.style.maxHeight = '0';
          // Re-measure after the collapse animation finishes
          setTimeout(remeasureParent, 300);
        } else {
          // Remove collapsed class FIRST to restore padding
          header.classList.remove('collapsed');
          animateExpand(content);

          // Unconstrained while the child animates; pinned once it settles
          const parentContent = expandedParentContent();
          if (parentContent) {
            parentContent.style.maxHeight = 'none';
          }
          setTimeout(remeasureParent, 300);
        }
      });
    });

    // Section max-heights are measured on demand (scrollHeight), so any
    // content that grows after measurement - cache status text wrapping to
    // another line, a longer Load Data label - stays clipped by the stale
    // cap unless something re-measures. Watching each section's children
    // (rather than the section itself) catches those growths as they
    // happen, and never fires for the collapse/expand animations, which
    // resize the section without moving its children.
    const unclipSectionContent = (content, controller) => {
      if (!content || !controller || controller.classList.contains('collapsed')) return;
      const cap = parseFloat(content.style.maxHeight);
      if (Number.isNaN(cap) || content.scrollHeight <= cap) return;

      content.style.transition = 'none';
      content.style.maxHeight = 'none';
      void content.offsetHeight;
      const height = content.scrollHeight;
      content.style.transition = '';
      if (height > 0) content.style.maxHeight = `${height}px`;
    };

    const contentResizeObserver = new ResizeObserver(entries => {
      for (const entry of entries) {
        const content = entry.target.parentElement;
        if (!content || !content.classList.contains('section-content') &&
            !content.classList.contains('sub-section-content')) continue;
        unclipSectionContent(content, content.previousElementSibling);
      }
    });

    document.querySelectorAll('.section-content, .sub-section-content').forEach(content => {
      Array.from(content.children).forEach(child => contentResizeObserver.observe(child));
    });

    // One shared resize handler instead of one listener per toggle
    window.addEventListener('resize', recalculateAllSectionHeights);
  }

