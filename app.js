  /**
   * Load configuration from JSON files with priority:
   * 1. First, try environment.json (generated by entrypoint from APP_* env vars)
   * 2. Then, try config.json and merge it (overwriting env values)
   * At least one file must be present with api.url set.
   *
   * Both files use the same JSON structure - no mapping needed.
   */
  async function loadEnvironmentConfig() {
    let hasConfig = false;

    function deepMerge(target, source) {
      for (const key in source) {
        if (source[key] && typeof source[key] === 'object' && !Array.isArray(source[key])) {
          if (!target[key]) target[key] = {};
          deepMerge(target[key], source[key]);
        } else {
          target[key] = source[key];
        }
      }
      return target;
    }

    // Step 1: Try to load environment.json first to set up base CONFIG
    try {
      const response = await fetch('environment.json');
      if (response.ok) {
        const envConfig = await response.json();

        window.CONFIG = envConfig;
        hasConfig = true;
        log('Loaded configuration from environment.json');
      }
    } catch (error) {
      // environment.json doesn't exist or failed to load - this is fine
      log('Could not load environment.json (will try config.json):', error.message);
    }

    // Step 2: Try to load config.json and merge it (overwrites env values)
    try {
      const response = await fetch('config.json');
      if (response.ok) {
        const fileConfig = await response.json();

        const baseConfig = window.CONFIG || {};
        window.CONFIG = deepMerge(baseConfig, fileConfig);
        hasConfig = true;
        log('Loaded config.json (merged with environment.json, config.json takes precedence)');
      }
    } catch (error) {
      // config.json doesn't exist or failed to load - this is fine if we have environment.json
      log('Could not load config.json:', error.message);
    }

    // Validate that at least one config source exists
    if (!hasConfig) {
      throw new Error('No configuration found. For Docker: set APP_* environment variables. For standalone: create config.json with at least api.url set.');
    }

    return hasConfig;
  }

  function validateAuthConfig() {
    const api = window.CONFIG.api || {};

    // Check basic auth: if username is set, password must also be set (and vice versa)
    const hasUsername = api.username !== undefined;
    const hasPassword = api.password !== undefined;

    if (hasUsername !== hasPassword) {
      showError('Configuration error: Both username and password must be provided for basic authentication, or neither should be set.');
      return false;
    }

    // Check cookie auth: if cookieName is set, cookieValue must also be set (and vice versa)
    const hasCookieName = api.cookieName !== undefined;
    const hasCookieValue = api.cookieValue !== undefined;

    if (hasCookieName !== hasCookieValue) {
      showError('Configuration error: Both cookieName and cookieValue must be provided for cookie authentication, or neither should be set.');
      return false;
    }

    // Authentication is optional - no validation for "at least one method"
    return true;
  }

  async function init() {
    // Try to load configuration: environment.json first, then config.js (overwrites)
    try {
      await loadEnvironmentConfig();
    } catch (error) {
      showError(error.message);
      return;
    }

    // Check if API URL is set (required)
    if (!window.CONFIG.api || !window.CONFIG.api.url) {
      showError('Configuration error: API URL is required. Set API_URL in environment.json or api.url in config.json');
      return;
    }

    // Validate API URL is a properly formatted URL
    try {
      new URL(window.CONFIG.api.url);
    } catch (e) {
      showError('Configuration error: API URL is not a valid URL. Got: ' + window.CONFIG.api.url);
      return;
    }

    // Validate authentication configuration
    validateAuthConfig();

    // Load settings from localStorage
    loadSettings();

    // Initialize map
    initMap();

    // Initialize UI
    await initUI();

    // Restore sidebar state
    restoreSidebarState();

    // Apply theme
    applyTheme();

    // Listen for system theme changes
    initSystemThemeListener();

    // Set default dates
    setDefaultDates();

    // Fetch users and devices
    fetchUsersAndDevices();
  }

