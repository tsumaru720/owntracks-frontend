  // Load one user/device combo: refresh today if the range includes it,
  // then cached days, then API fetches for uncached ranges. `label` names
  // the combo in the loading overlay; returns points + cached/fresh counts.
  async function loadDataForCombo(user, device, fromDate, toDate, requestedDays, storageEnabled, label) {
    let comboData = [];
    let cachedCount = 0;
    let freshCount = 0;

    if (storageEnabled) {
      // If the range includes today, refresh today's cache before reading
      // it so newly recorded points are picked up
      const todayKey = formatDateForInput(new Date());
      let todayRefreshed = false;

      if (requestedDays.includes(todayKey)) {
        try {
          showLoading(`Updating today's data for ${label}...`);
          const todayFrom = new Date(todayKey + 'T00:00:00');
          const todayTo = new Date(todayKey + 'T23:59:59');

          log(`[Today Refresh] Fetching ${todayKey} for ${label}`);

          const todayData = await fetchLocations(user, device, todayFrom, todayTo);
          freshCount += todayData.length;

          // Cache the full day (even when empty) so it isn't re-requested below
          const dailyData = splitDataByDays(todayData, todayKey, todayKey);
          await cacheDailyData(user, device, dailyData);

          // Today is already counted as fresh - skip it when reading cache
          todayRefreshed = true;
          comboData = comboData.concat(todayData);
        } catch (e) {
          // Best-effort: fall back to whatever the cache holds for today
          logWarn(`Failed to refresh today's data for ${label}:`, e.message);
        }
      }

      // Load cached days
      const cachedDays = await getCachedDays(user, device);
      log('Requested days:', requestedDays);
      log('Cached days:', Array.from(cachedDays));
      const daysToLoad = requestedDays.filter(day =>
        cachedDays.has(day) && !(todayRefreshed && day === todayKey));
      log('Days to load from cache:', daysToLoad);

      if (daysToLoad.length > 0) {
        showLoading(`Loading ${label} (${daysToLoad.length} cached day${daysToLoad.length > 1 ? 's' : ''})...`);
        const cachedData = await loadCachedDays(user, device, daysToLoad);
        cachedCount = cachedData.length;
        comboData = comboData.concat(cachedData);
      }
    }

    // Find uncached day ranges
    const uncachedRanges = storageEnabled
      ? await getUncachedDayRanges(user, device, requestedDays)
      : [{ from: fromDate, to: toDate }];

    log('Uncached ranges:', uncachedRanges);

    // Fetch uncached data
    for (const range of uncachedRanges) {
      const daysInThisRange = getDaysInRange(range.from, range.to);
      showLoading(
        `Fetching ${label} (${daysInThisRange.length} day${daysInThisRange.length > 1 ? 's' : ''} from API)...`,
        'This may take several minutes for large date ranges.'
      );

      log(`[Date Debug] Requested local range: ${range.from} to ${range.to}`);

      const rangeFrom = new Date(range.from + 'T00:00:00');
      const rangeTo = new Date(range.to + 'T23:59:59');
      const rangeData = await fetchLocations(user, device, rangeFrom, rangeTo);

      // Track fresh point count
      freshCount += rangeData.length;

      // Cache the data by day if storage is enabled
      if (storageEnabled && rangeData.length > 0) {
        const dailyData = splitDataByDays(rangeData, range.from, range.to);
        await cacheDailyData(user, device, dailyData);
      }

      comboData = comboData.concat(rangeData);
    }

    return { data: comboData, cachedCount, freshCount };
  }

  async function loadData() {
    clearHeaderError();
    const userSel = document.getElementById('userSelect').value;
    const deviceSel = document.getElementById('deviceSelect').value;

    // "All Users" implies "All Devices"; otherwise both must be selected
    if (!userSel || (userSel !== ALL_SELECTOR && !deviceSel)) {
      showError('Please select both user and device.');
      return;
    }

    const combos = await resolveSelectedCombos();
    if (combos.length === 0) {
      showError('No user/device combinations found for this selection.');
      return;
    }

    const { from, to } = getDateRange();
    const fromDate = formatDateForInput(from);
    const toDate = formatDateForInput(to);
    const requestedDays = getDaysInRange(fromDate, toDate);

    try {
      // Check if storage is enabled
      const storageEnabled = getSetting('storageEnabled', true);

      let cachedPointCount = 0;
      let freshPointCount = 0;
      const multi = combos.length > 1;
      const comboChunks = [];

      for (let i = 0; i < combos.length; i++) {
        const { user, device } = combos[i];
        const label = multi ? `${i + 1}/${combos.length} ${user}/${device}` : `${user}/${device}`;

        const comboResult = await loadDataForCombo(
          user, device, fromDate, toDate, requestedDays, storageEnabled, label
        );

        // Tag points with their source so tracks can be kept contiguous
        comboResult.data.forEach(point => {
          point.user = user;
          point.device = device;
        });

        // Timestamp order within a combo: a numeric per-combo sort is far
        // cheaper than a locale-aware (user, device, tst) comparator run
        // against every point
        comboResult.data.sort((a, b) => a.tst - b.tst);

        cachedPointCount += comboResult.cachedCount;
        freshPointCount += comboResult.freshCount;
        comboChunks.push(comboResult.data);
      }

      // Combos were fetched in list order - order them alphabetically so
      // each user/device track stays contiguous (route lines don't jump
      // between devices)
      comboChunks.sort((a, b) => {
        const userCmp = String(a[0]?.user || '').localeCompare(String(b[0]?.user || ''));
        if (userCmp !== 0) return userCmp;
        return String(a[0]?.device || '').localeCompare(String(b[0]?.device || ''));
      });

      // Push rather than concat - repeated concat re-copies the whole
      // array per combo, and a large spread exceeds the argument limit
      const allData = [];
      for (const chunk of comboChunks) {
        for (let i = 0; i < chunk.length; i++) {
          allData.push(chunk[i]);
        }
      }
      state.data.raw = allData;

      // Store source breakdown for indicator
      state.data.sourceBreakdown = {
        cached: cachedPointCount,
        fresh: freshPointCount
      };

      // Handle empty results
      if (state.data.raw.length === 0) {
        // Clear data layers (keeps the current map position)
        clearMapData();
        hideLoading();
        updateHeaderStatus('No data found for selected date range');
        return;
      }

      document.getElementById('qaRecenter').disabled = false;

      // Single pass for time range and max accuracy. No Math.min(...spread):
      // spreading a large array exceeds the argument limit (issue #3)
      let tstMin = Infinity;
      let tstMax = -Infinity;
      state.data.maxAccuracy = 0;
      state.data.raw.forEach(point => {
        if (point.tst < tstMin) tstMin = point.tst;
        if (point.tst > tstMax) tstMax = point.tst;
        if (point.acc && point.acc > state.data.maxAccuracy) {
          state.data.maxAccuracy = point.acc;
        }
      });
      state.data.timeRange = { start: tstMin, end: tstMax };

      const sliderMax = Math.max(500, Math.ceil(state.data.maxAccuracy / 10) * 10);
      document.getElementById('accuracySlider').max = sliderMax;

      applyAccuracyFilter();

      updateStats();
      await updateRefreshButton();

      redrawMap();

      hideLoading();

      // Fit map to data bounds if setting is enabled, otherwise restore saved position
      if (getSetting('autoFitToBounds', true) && state.data.filtered.length > 0) {
        fitMapToBounds();
      } else {
        restoreMapPosition();
      }

      // Clear any stale status message now that data has loaded successfully
      updateHeaderStatus('');

    } catch (error) {
      showLoadingError('Failed to load locations: ' + error.message);
      setTimeout(() => {
        hideLoading();
        clearMapData();
        showError('Failed to load locations: ' + error.message);
      }, 3000);
    }
  }

