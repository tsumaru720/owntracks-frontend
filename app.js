  // Repopulate the device dropdown for the selected user. Selection
  // priority: saved device > config default > the only device > "-". With
  // "All Users" the dropdown hides (treated as "All Devices") but every
  // user's device list is still fetched for "Load Data".
  async function updateDeviceSelect() {
    clearHeaderError();
    const userSelect = document.getElementById('userSelect');
    const deviceSelect = document.getElementById('deviceSelect');
    const deviceGroup = document.getElementById('deviceFormGroup');
    const user = userSelect.value;
    const allUsers = user === ALL_SELECTOR;

    // The device selection is irrelevant for "All Users" - hide the dropdown
    // and treat the selection as "All Devices"
    deviceGroup.style.display = allUsers ? 'none' : '';

    const recalcHeights = () => {
      requestAnimationFrame(() => {
        requestAnimationFrame(() => {
          recalculateAllSectionHeights();
        });
      });
    };

    // No user selected - devices can't be known yet
    if (!user) {
      deviceSelect.innerHTML = '';
      const placeholder = document.createElement('option');
      placeholder.value = '';
      placeholder.textContent = '-';
      deviceSelect.appendChild(placeholder);
      deviceSelect.value = '';
      recalcHeights();
      return;
    }

    try {
      if (allUsers) {
        showLoading('Loading devices for all users...');

        // Fetch every user's device list in parallel for later enumeration
        const results = await Promise.allSettled(
          state.data.users.map(u => fetchDevicesForUser(u))
        );
        results.forEach((result, i) => {
          if (result.status !== 'fulfilled') {
            logWarn(`Failed to fetch devices for ${state.data.users[i]}:`, result.reason?.message);
          }
        });

        // Dropdown stays hidden - just keep it consistent with "All Devices"
        deviceSelect.innerHTML = '';
        const placeholder = document.createElement('option');
        placeholder.value = '';
        placeholder.textContent = '-';
        deviceSelect.appendChild(placeholder);
        const allDevicesOption = document.createElement('option');
        allDevicesOption.value = ALL_SELECTOR;
        allDevicesOption.textContent = 'All Devices';
        deviceSelect.appendChild(allDevicesOption);
        deviceSelect.value = ALL_SELECTOR;
      } else {
        showLoading(`Loading devices for ${user}...`);
        const devices = await fetchDevicesForUser(user);

        // Populate device dropdown: "-" placeholder, "All Devices", then each device
        deviceSelect.innerHTML = '';

        const devicePlaceholder = document.createElement('option');
        devicePlaceholder.value = '';
        devicePlaceholder.textContent = '-';
        deviceSelect.appendChild(devicePlaceholder);

        const allDevicesOption = document.createElement('option');
        allDevicesOption.value = ALL_SELECTOR;
        allDevicesOption.textContent = 'All Devices';
        deviceSelect.appendChild(allDevicesOption);

        devices.forEach(device => {
          const option = document.createElement('option');
          option.value = device;
          option.textContent = device;
          deviceSelect.appendChild(option);
        });

        const savedDevice = getSetting('selectedDevice', '');
        const defaultDevice = window.CONFIG.defaults?.device;
        let deviceToSelect = '';

        if (savedDevice === ALL_SELECTOR || (savedDevice && devices.includes(savedDevice))) {
          deviceToSelect = savedDevice;
        } else if (defaultDevice && devices.includes(defaultDevice)) {
          deviceToSelect = defaultDevice;
        } else if (devices.length === 1) {
          deviceToSelect = devices[0];
        }

        deviceSelect.value = deviceToSelect;
        // No saveSetting here: only explicit user changes are persisted
      }

      recalcHeights();
      hideLoading();

    } catch (error) {
      showLoadingError('Failed to load devices: ' + error.message);
      setTimeout(() => {
        hideLoading();
        showError('Failed to load devices: ' + error.message);
      }, 3000);
    }
  }

  // Page-load restore: if any combo of the current selection has cached
  // days inside the requested date range, render that data straight from the
  // cache - no API traffic. Uncached days and the current day's points
  // stay blank until an explicit Load Data (which fetches the current day
  // fresh and fills the gaps) or Refresh from API. Only runs once at page load;
  // in-session selection changes just refresh the Load Data button state
  // via updateRefreshButton.
  async function autoLoadFromCache() {
    if (!getSetting('storageEnabled', true)) {
      await updateRefreshButton();
      return;
    }

    const combos = await resolveSelectedCombos();
    if (combos.length === 0) {
      await updateRefreshButton();
      return;
    }

    const { from, to } = getDateRange();
    const requestedDays = getDaysInRange(formatDateForInput(from), formatDateForInput(to));

    for (const { user, device } of combos) {
      const cachedDays = await getCachedDays(user, device);
      if (requestedDays.some(day => cachedDays.has(day))) {
        await loadData({ cacheOnly: true });
        return;
      }
    }

    // Nothing cached for this selection - still refresh the buttons
    await updateRefreshButton();
  }

  // Expand the current selection into the concrete user/device combos to
  // load ("All Users"/"All Devices" expand to every match)
  async function resolveSelectedCombos() {
    const userSel = document.getElementById('userSelect').value;
    // "All Users" always implies "All Devices" (the device dropdown is hidden)
    const deviceSel = userSel === ALL_SELECTOR
      ? ALL_SELECTOR
      : document.getElementById('deviceSelect').value;

    if (!userSel || !deviceSel) {
      return [];
    }

    const users = userSel === ALL_SELECTOR ? state.data.users : [userSel];
    const combos = [];

    for (const user of users) {
      let devices = state.data.devicesByUser[user];
      if (devices === undefined) {
        try {
          devices = await fetchDevicesForUser(user);
        } catch (e) {
          logWarn(`Failed to fetch device list for ${user}:`, e.message);
          devices = [];
        }
      }

      if (deviceSel === ALL_SELECTOR) {
        devices.forEach(device => combos.push({ user, device }));
      } else if (devices.includes(deviceSel)) {
        combos.push({ user, device: deviceSel });
      }
    }

    return combos;
  }

  // Fetch locations for one user/device. Boundaries are local-time Dates
  // (e.g. local midnight / local end of day), converted to UTC for the API.
  async function fetchLocations(user, device, rangeFrom, rangeTo) {
    const fromStr = formatDateForAPI(rangeFrom, 'start');
    const toStr = formatDateForAPI(rangeTo, 'end');

    log(`[Date Debug] API Request: User ${user}, Device ${device}`);
    log(`[Date Debug] Local date objects: ${rangeFrom.toLocaleString()} to ${rangeTo.toLocaleString()}`);
    log(`[Date Debug] UTC for API: from=${fromStr}, to=${toStr}`);

    const url = `${window.CONFIG.api.url}/api/0/locations?` +
      `from=${encodeURIComponent(fromStr)}&` +
      `to=${encodeURIComponent(toStr)}&` +
      `user=${encodeURIComponent(user)}&` +
      `device=${encodeURIComponent(device)}&` +
      `format=json`;

    const response = await fetchWithTimeout(url, {
      headers: buildAuthHeaders()
    });

    if (!response.ok) {
      throw new Error(`Failed to fetch locations: ${response.status}`);
    }

    const result = await response.json();
    return result.data || [];
  }

  // Load one user/device combo: cached days first, then API fetches for
  // uncached ranges. `label` names the combo in the loading overlay;
  // returns points + cached/fresh counts. `cacheOnly` (page-load
  // auto-restore) serves purely from the cache - no API traffic; gaps and
  // the current day wait for an explicit Load Data.
  async function loadDataForCombo(user, device, fromDate, toDate, requestedDays, storageEnabled, label, cacheOnly = false) {
    let comboData = [];
    let cachedCount = 0;
    let freshCount = 0;

    // The current day is never cached: it's incomplete by nature, and a
    // partial-day key would stop the gap fill from ever completing it. It
    // rides along as the trailing uncached day of every load while in
    // range (fetched fresh, display-only) and gets cached complete from
    // tomorrow onwards.
    const todayKey = formatDateForInput(new Date());

    if (storageEnabled) {
      // Load cached days
      const cachedDays = await getCachedDays(user, device);
      log('Requested days:', requestedDays);
      log('Cached days:', Array.from(cachedDays));
      const daysToLoad = requestedDays.filter(day => cachedDays.has(day));
      log('Days to load from cache:', daysToLoad);

      if (daysToLoad.length > 0) {
        showLoading(`Loading ${label} (${daysToLoad.length} cached day${daysToLoad.length > 1 ? 's' : ''})...`);
        const cachedData = await loadCachedDays(user, device, daysToLoad);
        cachedCount = cachedData.length;
        comboData = comboData.concat(cachedData);
      }
    }

    // Find uncached day ranges (skipped in cache-only mode - gaps stay
    // blank until an explicit Load Data / Refresh)
    if (!cacheOnly) {
      const uncachedRanges = storageEnabled
        ? await getUncachedDayRanges(user, device, requestedDays)
        : [{ from: fromDate, to: toDate }];

      log('Uncached ranges:', uncachedRanges);

      // Fetch uncached data
      for (const range of uncachedRanges) {
        const daysInThisRange = getDaysInRange(range.from, range.to);
        showLoading(
          `Fetching ${label} (${daysInThisRange.length} day${daysInThisRange.length > 1 ? 's' : ''} from API)...`,
          'This may take several minutes for large date ranges.'
        );

        log(`[Date Debug] Requested local range: ${range.from} to ${range.to}`);

        const rangeFrom = new Date(range.from + 'T00:00:00');
        const rangeTo = new Date(range.to + 'T23:59:59');
        const rangeData = await fetchLocations(user, device, rangeFrom, rangeTo);

        // Track fresh point count
        freshCount += rangeData.length;

        // Cache every day in the range, even when the fetch returned
        // nothing - the day key's existence marks the range complete so
        // it isn't re-requested; the cache status counts only days that
        // actually hold points
        if (storageEnabled) {
          const dailyData = splitDataByDays(rangeData, range.from, range.to);
          // Never persist the current day (see the note at the top of this
          // function) - its points stay fresh-only until the day is over
          delete dailyData[todayKey];
          await cacheDailyData(user, device, dailyData);
        }

        comboData = comboData.concat(rangeData);
      }
    }

    return { data: comboData, cachedCount, freshCount };
  }

  // Options: { cacheOnly } - serve exclusively from the cache with no API
  // traffic (page-load auto-restore). Takes an options object so a click
  // event can't leak through as a truthy flag.
  async function loadData({ cacheOnly = false } = {}) {
    clearHeaderError();
    const userSel = document.getElementById('userSelect').value;
    const deviceSel = document.getElementById('deviceSelect').value;

    // "All Users" implies "All Devices"; otherwise both must be selected
    if (!userSel || (userSel !== ALL_SELECTOR && !deviceSel)) {
      showError('Please select both user and device.');
      return;
    }

    const combos = await resolveSelectedCombos();
    if (combos.length === 0) {
      showError('No user/device combinations found for this selection.');
      return;
    }

    const { from, to } = getDateRange();
    const fromDate = formatDateForInput(from);
    const toDate = formatDateForInput(to);
    const requestedDays = getDaysInRange(fromDate, toDate);

    try {
      // Check if storage is enabled
      const storageEnabled = getSetting('storageEnabled', true);

      let cachedPointCount = 0;
      let freshPointCount = 0;
      const multi = combos.length > 1;
      const comboChunks = [];

      for (let i = 0; i < combos.length; i++) {
        const { user, device } = combos[i];
        const label = multi ? `${i + 1}/${combos.length} ${user}/${device}` : `${user}/${device}`;

        const comboResult = await loadDataForCombo(
          user, device, fromDate, toDate, requestedDays, storageEnabled, label, cacheOnly
        );

        // Tag points with their source so tracks can be kept contiguous
        comboResult.data.forEach(point => {
          point.user = user;
          point.device = device;
        });

        // Timestamp order within a combo: a numeric per-combo sort is far
        // cheaper than a locale-aware (user, device, tst) comparator run
        // against every point
        comboResult.data.sort((a, b) => a.tst - b.tst);

        cachedPointCount += comboResult.cachedCount;
        freshPointCount += comboResult.freshCount;
        comboChunks.push(comboResult.data);
      }

      // Combos were fetched in list order - order them alphabetically so
      // each user/device track stays contiguous (route lines don't jump
      // between devices)
      comboChunks.sort((a, b) => {
        const userCmp = String(a[0]?.user || '').localeCompare(String(b[0]?.user || ''));
        if (userCmp !== 0) return userCmp;
        return String(a[0]?.device || '').localeCompare(String(b[0]?.device || ''));
      });

      // Push rather than concat - repeated concat re-copies the whole
      // array per combo, and a large spread exceeds the argument limit
      const allData = [];
      for (const chunk of comboChunks) {
        for (let i = 0; i < chunk.length; i++) {
          allData.push(chunk[i]);
        }
      }
      state.data.raw = allData;

      // Store source breakdown for indicator
      state.data.sourceBreakdown = {
        cached: cachedPointCount,
        fresh: freshPointCount
      };

      // Handle empty results
      if (state.data.raw.length === 0) {
        // Clear data layers (keeps the current map position)
        clearMapData();
        hideLoading();
        updateHeaderStatus('No data found for selected date range');
        return;
      }

      document.getElementById('qaRecenter').disabled = false;

      // Single pass for time range, accuracy range and altitude range. No
      // Math.min(...spread): spreading a large array exceeds the argument
      // limit (issue #3)
      let tstMin = Infinity;
      let tstMax = -Infinity;
      let accMin = Infinity;
      let accMax = -Infinity;
      let altMin = Infinity;
      let altMax = -Infinity;
      state.data.raw.forEach(point => {
        if (point.tst < tstMin) tstMin = point.tst;
        if (point.tst > tstMax) tstMax = point.tst;
        // acc of 0/undefined means "no accuracy reported" - skip like the filter does
        if (point.acc) {
          if (point.acc < accMin) accMin = point.acc;
          if (point.acc > accMax) accMax = point.acc;
        }
        if (typeof point.alt === 'number' && !Number.isNaN(point.alt)) {
          if (point.alt < altMin) altMin = point.alt;
          if (point.alt > altMax) altMax = point.alt;
        }
      });
      state.data.timeRange = { start: tstMin, end: tstMax };
      state.data.accuracyRange = accMin === Infinity
        ? { min: null, max: null }
        : { min: accMin, max: accMax };
      state.data.altitudeRange = altMin === Infinity
        ? { min: null, max: null }
        : { min: altMin, max: altMax };

      // Pin the stepped scales to the new data's ranges, then - unless
      // this is the boot-time cache restore, which re-renders the
      // session the user left (filters included) - reset the meter
      // filters to "show all" (persisted) and re-pin the gradient
      // window to the new range at full span
      accuracyCtl.rebuild(buildAccuracySteps(state.data.accuracyRange.max), getSetting('accuracyMaxMeters', 0));
      altitudeCtl.rebuild(buildAltitudeSteps(state.data.altitudeRange.max), getSetting('minAltitudeMeters', 0));
      const altRange = state.data.altitudeRange;
      const hasAltitude = altRange.min !== null && altRange.min !== undefined;
      if (!cacheOnly) {
        saveSetting('accuracyMaxMeters', 0, 0);
        saveSetting('minAltitudeMeters', 0, 0);
        accuracyCtl.rebuild(buildAccuracySteps(state.data.accuracyRange.max), 0);
        altitudeCtl.rebuild(buildAltitudeSteps(state.data.altitudeRange.max), 0);
        if (hasAltitude) {
          saveSetting('altitudeMin', Math.floor(altRange.min), 0);
          saveSetting('altitudeMax', Math.ceil(altRange.max), 1000);
        }
      }
      if (hasAltitude) {
        syncAltitudeGradient(Math.floor(altRange.min), Math.ceil(altRange.max));
      }

      applyAccuracyFilter();

      updateStats();
      await updateRefreshButton();

      redrawMap();

      hideLoading();

      // Fit map to data bounds if setting is enabled, otherwise restore saved position
      if (getSetting('autoFitToBounds', true) && state.data.filtered.length > 0) {
        fitMapToBounds();
      } else {
        restoreMapPosition();
      }

      // Clear any stale status message now that data has loaded successfully
      updateHeaderStatus('');

    } catch (error) {
      showLoadingError('Failed to load locations: ' + error.message);
      setTimeout(() => {
        hideLoading();
        clearMapData();
        showError('Failed to load locations: ' + error.message);
      }, 3000);
    }
  }

