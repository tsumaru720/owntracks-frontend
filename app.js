  // Resolve a named preset against the current moment; boundaries are
  // local time (UTC conversion happens at query time)
  function resolveDatePreset(preset) {
    const now = new Date();
    const to = new Date(now);
    to.setHours(23, 59, 59, 999);

    const startDaysAgo = (days) => {
      const d = new Date(now);
      d.setDate(d.getDate() - days);
      d.setHours(0, 0, 0, 0);
      return d;
    };

    switch (preset) {
      case 'today':
        return { from: startDaysAgo(0), to };
      case '2days':
        return { from: startDaysAgo(1), to };
      case '7days':
        return { from: startDaysAgo(6), to };
      case '30days':
        return { from: startDaysAgo(29), to };
      case '90days':
        return { from: startDaysAgo(89), to };
      case '6months': {
        const from = new Date(now);
        from.setMonth(from.getMonth() - 6);
        from.setHours(0, 0, 0, 0);
        return { from, to };
      }
      case '1year': {
        const from = new Date(now);
        from.setFullYear(from.getFullYear() - 1);
        from.setHours(0, 0, 0, 0);
        return { from, to };
      }
      case 'all':
        // Start of the epoch (1970-01-01T00:00:00Z) through end of today
        return { from: new Date(0), to };
      default:
        return { from: startDaysAgo(29), to };
    }
  }

